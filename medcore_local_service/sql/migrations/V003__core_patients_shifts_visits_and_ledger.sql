CREATE TABLE IF NOT EXISTS mc_patients (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    hospital_code VARCHAR(64) NOT NULL,
    mrn VARCHAR(64) NOT NULL,
    full_name VARCHAR(191) NOT NULL,
    gender VARCHAR(16) NOT NULL DEFAULT 'male',
    date_of_birth DATE NULL,
    age INT NULL,
    phone VARCHAR(64) NOT NULL,
    national_id VARCHAR(64) NULL,
    blood_group VARCHAR(16) NULL,
    address TEXT NULL,
    insurance_company_id VARCHAR(64) NULL,
    insurance_policy_no VARCHAR(64) NULL,
    assigned_doctor_id BIGINT UNSIGNED NULL,
    department_id VARCHAR(64) NULL,
    balance DECIMAL(14,4) NOT NULL DEFAULT 0.0000,
    created_by BIGINT UNSIGNED NULL,
    is_deleted TINYINT(1) NOT NULL DEFAULT 0,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uq_mc_patients_hosp_mrn (hospital_code, mrn),
    KEY idx_mc_patients_hosp_phone (hospital_code, phone),
    KEY idx_mc_patients_hosp_doc (hospital_code, assigned_doctor_id),
    KEY idx_mc_patients_hosp_dept (hospital_code, department_id),
    KEY idx_mc_patients_hosp_creator (hospital_code, created_by),
    CONSTRAINT fk_mc_patients_tenant FOREIGN KEY (hospital_code) REFERENCES mc_tenants (hospital_code) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS mc_shifts (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    hospital_code VARCHAR(64) NOT NULL,
    shift_code VARCHAR(64) NOT NULL,
    cashier_staff_id BIGINT UNSIGNED NOT NULL,
    device_id VARCHAR(128) NULL,
    status ENUM('OPEN', 'CLOSING_REVIEW', 'CLOSED', 'HANDED_OVER') NOT NULL DEFAULT 'OPEN',
    opening_balance DECIMAL(14,4) NOT NULL DEFAULT 0.0000,
    cash_in DECIMAL(14,4) NOT NULL DEFAULT 0.0000,
    cash_out DECIMAL(14,4) NOT NULL DEFAULT 0.0000,
    expected_cash DECIMAL(14,4) NOT NULL DEFAULT 0.0000,
    counted_cash DECIMAL(14,4) NULL,
    variance_amount DECIMAL(14,4) NULL,
    opened_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at DATETIME NULL,
    closed_by BIGINT UNSIGNED NULL,
    notes TEXT NULL,
    UNIQUE KEY uq_mc_shifts_hosp_code (hospital_code, shift_code),
    KEY idx_mc_shifts_hosp_cashier_status (hospital_code, cashier_staff_id, status),
    CONSTRAINT fk_mc_shifts_cashier FOREIGN KEY (cashier_staff_id) REFERENCES mc_staff (id) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS mc_visits (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    hospital_code VARCHAR(64) NOT NULL,
    visit_number VARCHAR(64) NOT NULL,
    invoice_number VARCHAR(64) NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    patient_id BIGINT UNSIGNED NOT NULL,
    doctor_id BIGINT UNSIGNED NULL,
    department_id VARCHAR(64) NULL,
    clinic_id VARCHAR(64) NULL,
    shift_id BIGINT UNSIGNED NULL,
    appointment_id BIGINT UNSIGNED NULL,
    visit_type VARCHAR(32) NOT NULL DEFAULT 'OUTPATIENT',
    status VARCHAR(32) NOT NULL DEFAULT 'ACTIVE',
    clinical_status VARCHAR(32) NOT NULL DEFAULT 'WAITING',
    gross_amount DECIMAL(14,4) NOT NULL DEFAULT 0.0000,
    discount_amount DECIMAL(14,4) NOT NULL DEFAULT 0.0000,
    net_amount DECIMAL(14,4) NOT NULL DEFAULT 0.0000,
    insurance_covered_amount DECIMAL(14,4) NOT NULL DEFAULT 0.0000,
    patient_responsibility_amount DECIMAL(14,4) NOT NULL DEFAULT 0.0000,
    paid_amount DECIMAL(14,4) NOT NULL DEFAULT 0.0000,
    balance_amount DECIMAL(14,4) NOT NULL DEFAULT 0.0000,
    currency VARCHAR(16) NOT NULL DEFAULT 'EGP',
    created_by BIGINT UNSIGNED NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uq_mc_visits_hosp_number (hospital_code, visit_number),
    UNIQUE KEY uq_mc_visits_hosp_idemp (hospital_code, idempotency_key),
    KEY idx_mc_visits_hosp_patient (hospital_code, patient_id),
    KEY idx_mc_visits_hosp_doctor (hospital_code, doctor_id),
    KEY idx_mc_visits_hosp_shift (hospital_code, shift_id),
    CONSTRAINT fk_mc_visits_patient FOREIGN KEY (patient_id) REFERENCES mc_patients (id) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_mc_visits_shift FOREIGN KEY (shift_id) REFERENCES mc_shifts (id) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS mc_visit_items (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    hospital_code VARCHAR(64) NOT NULL,
    visit_id BIGINT UNSIGNED NOT NULL,
    item_type VARCHAR(32) NOT NULL DEFAULT 'SERVICE',
    service_code VARCHAR(64) NOT NULL,
    service_name VARCHAR(191) NOT NULL,
    doctor_id BIGINT UNSIGNED NULL,
    quantity DECIMAL(12,4) NOT NULL DEFAULT 1.0000,
    unit_price DECIMAL(14,4) NOT NULL DEFAULT 0.0000,
    gross_amount DECIMAL(14,4) NOT NULL DEFAULT 0.0000,
    discount_amount DECIMAL(14,4) NOT NULL DEFAULT 0.0000,
    net_amount DECIMAL(14,4) NOT NULL DEFAULT 0.0000,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    KEY idx_mc_visit_items_hosp_visit (hospital_code, visit_id),
    CONSTRAINT fk_mc_visit_items_visit FOREIGN KEY (visit_id) REFERENCES mc_visits (id) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS mc_visit_item_cost_lines (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    hospital_code VARCHAR(64) NOT NULL,
    visit_id BIGINT UNSIGNED NOT NULL,
    visit_item_id BIGINT UNSIGNED NOT NULL,
    component_type ENUM('SERVICE_LABOR', 'CONSUMABLE_MATERIAL', 'EQUIPMENT_FEE') NOT NULL,
    inventory_item_id BIGINT UNSIGNED NULL,
    stock_batch_id BIGINT UNSIGNED NULL,
    stock_movement_id BIGINT UNSIGNED NULL,
    quantity DECIMAL(12,4) NOT NULL DEFAULT 1.0000,
    unit_cost_fifo DECIMAL(14,4) NOT NULL DEFAULT 0.0000,
    total_cost_fifo DECIMAL(14,4) NOT NULL DEFAULT 0.0000,
    billed_gross_amount DECIMAL(14,4) NOT NULL DEFAULT 0.0000,
    billed_net_amount DECIMAL(14,4) NOT NULL DEFAULT 0.0000,
    is_commissionable TINYINT(1) NOT NULL DEFAULT 1,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    KEY idx_mc_vicl_hosp_visit (hospital_code, visit_id),
    KEY idx_mc_vicl_visit_item (visit_item_id),
    CONSTRAINT fk_mc_vicl_visit FOREIGN KEY (visit_id) REFERENCES mc_visits (id) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_mc_vicl_visit_item FOREIGN KEY (visit_item_id) REFERENCES mc_visit_items (id) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS mc_financial_events (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    event_uuid VARCHAR(64) NOT NULL,
    hospital_code VARCHAR(64) NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    event_type VARCHAR(64) NOT NULL,
    source_module VARCHAR(64) NOT NULL,
    source_entity_type VARCHAR(64) NOT NULL,
    source_entity_id BIGINT UNSIGNED NOT NULL,
    shift_id BIGINT UNSIGNED NULL,
    gross_amount DECIMAL(14,4) NOT NULL DEFAULT 0.0000,
    discount_amount DECIMAL(14,4) NOT NULL DEFAULT 0.0000,
    net_amount DECIMAL(14,4) NOT NULL DEFAULT 0.0000,
    paid_amount DECIMAL(14,4) NOT NULL DEFAULT 0.0000,
    insurance_covered_amount DECIMAL(14,4) NOT NULL DEFAULT 0.0000,
    patient_responsibility_amount DECIMAL(14,4) NOT NULL DEFAULT 0.0000,
    balance_amount DECIMAL(14,4) NOT NULL DEFAULT 0.0000,
    commission_basis_type VARCHAR(32) NULL,
    commission_basis_amount DECIMAL(14,4) NOT NULL DEFAULT 0.0000,
    commission_rate DECIMAL(10,4) NOT NULL DEFAULT 0.0000,
    commission_amount DECIMAL(14,4) NOT NULL DEFAULT 0.0000,
    currency VARCHAR(16) NOT NULL DEFAULT 'EGP',
    reversal_of_event_id BIGINT UNSIGNED NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'POSTED',
    created_by BIGINT UNSIGNED NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    UNIQUE KEY uq_mc_finev_uuid (event_uuid),
    UNIQUE KEY uq_mc_finev_hosp_idemp (hospital_code, idempotency_key),
    KEY idx_mc_finev_hosp_source (hospital_code, source_entity_type, source_entity_id),
    KEY idx_mc_finev_hosp_shift (hospital_code, shift_id),
    CONSTRAINT fk_mc_finev_shift FOREIGN KEY (shift_id) REFERENCES mc_shifts (id) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS mc_financial_postings (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    posting_uuid VARCHAR(64) NOT NULL,
    hospital_code VARCHAR(64) NOT NULL,
    event_id BIGINT UNSIGNED NOT NULL,
    posting_type VARCHAR(64) NOT NULL,
    account_bucket VARCHAR(64) NOT NULL,
    direction ENUM('DEBIT', 'CREDIT') NOT NULL,
    amount DECIMAL(14,4) NOT NULL DEFAULT 0.0000,
    beneficiary_type VARCHAR(32) NULL,
    beneficiary_id BIGINT UNSIGNED NULL,
    shift_id BIGINT UNSIGNED NULL,
    settlement_id BIGINT UNSIGNED NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'POSTED',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    UNIQUE KEY uq_mc_finpost_uuid (posting_uuid),
    KEY idx_mc_finpost_hosp_event (hospital_code, event_id),
    KEY idx_mc_finpost_hosp_beneficiary (hospital_code, beneficiary_type, beneficiary_id, status),
    KEY idx_mc_finpost_hosp_bucket (hospital_code, account_bucket, direction),
    CONSTRAINT fk_mc_finpost_event FOREIGN KEY (event_id) REFERENCES mc_financial_events (id) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
